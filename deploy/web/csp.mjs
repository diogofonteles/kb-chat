#!/usr/bin/env node
// Writes the Caddy snippet with the Content-Security-Policy of the built SPA (ADR 0010).
//   node deploy/web/csp.mjs apps/web/dist/browser/index.html > csp.caddy
// index.html has inline code the build controls (the theme script, the stylesheet onload
// swap): each one is allowed by its sha256, never with 'unsafe-inline' for scripts.
// Google Identity Services (KBC-010) needs its client script, style, iframe and XHR origin.
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';

const GIS = 'https://accounts.google.com/gsi/';

const sha256 = (text) =>
  `'sha256-${createHash('sha256').update(text, 'utf8').digest('base64')}'`;

/** Bodies of inline <script> elements (the ones without src). */
export const inlineScripts = (html) =>
  [...html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi)]
    .map((match) => match[1])
    .filter((body) => body.trim().length > 0);

/** Values of inline event handler attributes (onload="..."). */
export const inlineHandlers = (html) =>
  [...html.matchAll(/\son[a-z]+="([^"]*)"/gi)].map((match) => match[1]);

export function contentSecurityPolicy(html) {
  const scripts = inlineScripts(html).map(sha256);
  const handlers = inlineHandlers(html).map(sha256);
  const scriptSrc = [
    "'self'",
    ...scripts,
    ...(handlers.length > 0 ? ["'unsafe-hashes'", ...new Set(handlers)] : []),
    `${GIS}client`,
  ];
  return [
    "default-src 'self'",
    `script-src ${scriptSrc.join(' ')}`,
    // Angular injects component styles at runtime; styles cannot run code.
    `style-src 'self' 'unsafe-inline' https://fonts.googleapis.com ${GIS}style`,
    "font-src 'self' https://fonts.gstatic.com",
    // Vault documents may embed remote images in markdown.
    "img-src 'self' data: https:",
    `connect-src 'self' ${GIS}`,
    `frame-src ${GIS}`,
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join('; ');
}

const [, , indexPath] = process.argv;
if (indexPath) {
  const policy = contentSecurityPolicy(readFileSync(indexPath, 'utf8'));
  process.stdout.write(
    `# Generated by deploy/web/csp.mjs at build time; do not edit.\n` +
      `header Content-Security-Policy "${policy}"\n`,
  );
}
