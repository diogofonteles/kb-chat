import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import type { APIRequestContext, Browser, Page } from '@playwright/test';
import {
  CSRF,
  expect,
  invite,
  ownerApi,
  pageWith,
  test as base,
  type PageOptions,
  uniqueEmail,
} from './fixtures.js';

const ffmpeg = (): string =>
  process.env['FFMPEG_BIN'] ??
  execFileSync('/bin/sh', ['-c', 'command -v ffmpeg']).toString().trim();

const dir = mkdtempSync(join(tmpdir(), 'kbchat-e2e-audio-'));

/**
 * A real MP3 of `seconds` (a tone, generated by ffmpeg: no binary fixture in git). The
 * name is the title the upload panel suggests.
 */
export function makeMp3(
  name: string,
  seconds: number,
  options: {
    /** The lavfi source; a 330 Hz tone by default. */
    readonly source?: string;
    readonly bitrate?: string;
  } = {},
): string {
  const source = options.source ?? `sine=frequency=330:duration=${seconds}`;
  const bitrate = options.bitrate ?? '96k';
  const path = join(dir, `${name}.mp3`);
  execFileSync(ffmpeg(), [
    '-hide_banner',
    '-loglevel',
    'error',
    '-y',
    '-f',
    'lavfi',
    '-i',
    source,
    '-c:a',
    'libmp3lame',
    '-b:a',
    bitrate,
    // The same tone twice would be a repeated file in the shared collection (KBC-035 BR-2).
    '-metadata',
    `comment=${uniqueTag()}`,
    path,
  ]);
  return path;
}

/**
 * `makeMp3` for hours of audio: one minute encoded and repeated without encoding again.
 * Encoding it all takes most of a test's time limit on a CI runner.
 */
export function makeLongMp3(
  name: string,
  minutes: number,
  options: { readonly bitrate: string },
): string {
  const minute = makeMp3(`${name} minuto`, 60, options);
  const path = join(dir, `${name}.mp3`);
  execFileSync(ffmpeg(), [
    '-hide_banner',
    '-loglevel',
    'error',
    '-y',
    '-stream_loop',
    `${minutes - 1}`,
    '-i',
    minute,
    '-c',
    'copy',
    path,
  ]);
  return path;
}

/**
 * Real audio of about `bytes`, and only seconds of it: an upload test wants a size, and the
 * one worker of the run converts by length, so minutes here keep other tests waiting.
 */
export function makeHeavyWav(name: string, bytes: number): string {
  const seconds = Math.ceil(bytes / HEAVY_WAV_BYTES_PER_SECOND);
  const path = join(dir, `${name}.wav`);
  execFileSync(ffmpeg(), [
    '-hide_banner',
    '-loglevel',
    'error',
    '-y',
    '-f',
    'lavfi',
    '-i',
    `sine=frequency=330:sample_rate=192000:duration=${seconds}`,
    '-ac',
    '2',
    '-c:a',
    'pcm_s32le',
    '-metadata',
    `comment=${uniqueTag()}`,
    path,
  ]);
  return path;
}

/** 192 kHz, two channels, four bytes each. */
const HEAVY_WAV_BYTES_PER_SECOND = 192_000 * 2 * 4;

/** A tag no other parallel test shares (time plus randomness), for titles. */
export const uniqueTag = (): string =>
  `${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 7)}`;

export interface UploadedMedia {
  readonly id: string;
  readonly title: string;
}

/** A collection of its own: a list with only this test's media (KBC-096, no title search). */
export async function aCollection(api: APIRequestContext): Promise<string> {
  const created = await api.post('/api/v1/topics', {
    headers: CSRF,
    data: { title: `Zz Acervo ${uniqueTag()}` },
  });
  expect(created.status(), await created.text()).toBe(201);
  return ((await created.json()) as { slug: string }).slug;
}

/**
 * A collection of its own that also has a folder in the kb vault (KBC-100 AC-12): its track
 * documents are published there, as in a collection the owner made with kb.
 */
export async function aCollectionInVault(
  api: APIRequestContext,
): Promise<string> {
  const topic = await aCollection(api);
  const made = await api.post('/api/e2e/kb-publish/folder', {
    headers: CSRF,
    data: { topic },
  });
  expect(made.status(), await made.text()).toBe(204);
  return topic;
}

/**
 * A tone of `seconds` silenced over `pauses` ([start, end] in seconds), as the lavfi
 * source of `makeMp3` (KBC-044: pauses of known length).
 */
export const toneWithPauses = (
  seconds: number,
  pauses: readonly (readonly [number, number])[],
): string => {
  const silent = pauses.map(([from, to]) => `between(t,${from},${to})`);
  return `aevalsrc='if(${silent.join('+') || '0'},0,0.5*sin(2*PI*330*t))':s=44100:d=${seconds}`;
};

/** Uploads through the API (POST, then PUT of the bytes) and waits until it is ready. */
export async function uploadReady(
  api: APIRequestContext,
  input: {
    title: string;
    seconds: number;
    topic?: string;
    /** The lavfi source (KBC-044: a tone with pauses). */
    source?: string;
    /** A long tone at a low bitrate keeps the upload small (KBC-038 NFR-2). */
    bitrate?: string;
    /** How long to wait for the conversion (it slows down on a loaded machine). */
    readyWithinMs?: number;
    /**
     * Hours of tone as one minute repeated (`makeLongMp3`, whole minutes): encoding two
     * hours here took 14 s of the test for the same bytes the server converts.
     */
    looped?: boolean;
  },
): Promise<UploadedMedia> {
  const name = input.title.replace(/\W+/g, '-');
  if (input.looped && input.seconds % 60 !== 0)
    throw new Error(`looped audio needs whole minutes, not ${input.seconds} s`);
  const body = readFileSync(
    input.looped
      ? makeLongMp3(name, input.seconds / 60, {
          bitrate: input.bitrate ?? '96k',
        })
      : makeMp3(name, input.seconds, {
          source: input.source,
          bitrate: input.bitrate,
        }),
  );
  const created = await api.post(
    `/api/v1/topics/${input.topic ?? 'hermetismo'}/media`,
    {
      data: {
        title: input.title,
        author: null,
        fileName: 'aula.mp3',
        bytes: body.length,
      },
      headers: CSRF,
    },
  );
  expect(created.status(), await created.text()).toBe(201);
  const { id } = (await created.json()) as { id: string };
  const sent = await api.put(`/api/v1/media/${id}/file`, {
    data: body,
    headers: { ...CSRF, 'content-type': 'application/octet-stream' },
  });
  expect(sent.status(), await sent.text()).toBe(200);
  await expect
    .poll(
      async () =>
        (
          (await (await api.get(`/api/v1/media/${id}`)).json()) as {
            status: string;
          }
        ).status,
      {
        timeout: input.readyWithinMs ?? 120_000,
      },
    )
    .toBe('ready');
  return { id, title: input.title };
}

/** What the page's media element is doing (the engine's hidden <audio> or <video>). */
export async function audioState(page: Page) {
  return page.locator('[data-media-engine]').evaluate((element) => {
    const audio = element as HTMLMediaElement;
    return {
      tag: audio.tagName,
      currentTime: audio.currentTime,
      paused: audio.paused,
      ended: audio.ended,
      duration: audio.duration,
      src: audio.currentSrc,
    };
  });
}

/** The theme as the sidebar would set it, before the page loads. */
export async function useTheme(
  page: Page,
  theme: 'light' | 'dark' | 'esoteric',
) {
  await page.addInitScript(
    (value) => localStorage.setItem('kb-chat.theme', value),
    theme,
  );
}

/**
 * A person who may listen (KBC-041): speed and positions are per person, so each test
 * listens as its own new member and parallel tests never see each other's choices.
 */
export async function newListener(
  browser: Browser,
  options: PageOptions & { readonly email?: string },
): Promise<{ page: Page; email: string }> {
  const email = options.email ?? uniqueEmail('ouvinte');
  const owner = await ownerApi();
  await invite(owner, email, {
    topics: ['hermetismo'],
    features: ['search', 'media'],
  });
  await owner.dispose();
  return { page: await pageWith(browser, email, options), email };
}

/** Player specs: `page` is a fresh listener's, not the shared owner's. */
export const listenerTest = base.extend<{ page: Page }>({
  page: async (
    {
      browser,
      viewport,
    }: {
      browser: Browser;
      viewport: { width: number; height: number } | null;
    },
    use: (page: Page) => Promise<void>,
  ) => {
    const { page } = await newListener(browser, { viewport });
    await use(page);
    await page.context().close();
  },
});
