import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import type { APIRequestContext, Browser, Page } from '@playwright/test';
import {
  CSRF,
  expect,
  invite,
  ownerApi,
  pageWith,
  test as base,
  type PageOptions,
  uniqueEmail,
} from './fixtures.js';

const ffmpeg = (): string =>
  process.env['FFMPEG_BIN'] ??
  execFileSync('/bin/sh', ['-c', 'command -v ffmpeg']).toString().trim();

const dir = mkdtempSync(join(tmpdir(), 'kbchat-e2e-audio-'));

/**
 * A real MP3 of `seconds` (a tone, generated by ffmpeg: no binary fixture in git). The
 * name is the title the upload panel suggests.
 */
export function makeMp3(name: string, seconds: number): string {
  const path = join(dir, `${name}.mp3`);
  execFileSync(ffmpeg(), [
    '-hide_banner',
    '-loglevel',
    'error',
    '-y',
    '-f',
    'lavfi',
    '-i',
    `sine=frequency=330:duration=${seconds}`,
    '-c:a',
    'libmp3lame',
    '-b:a',
    '96k',
    path,
  ]);
  return path;
}

export interface UploadedMedia {
  readonly id: string;
  readonly title: string;
}

/** Uploads through the API (POST, then PUT of the bytes) and waits until it is ready. */
export async function uploadReady(
  api: APIRequestContext,
  input: { title: string; seconds: number; topic?: string },
): Promise<UploadedMedia> {
  const body = readFileSync(
    makeMp3(input.title.replace(/\W+/g, '-'), input.seconds),
  );
  const created = await api.post(
    `/api/v1/topics/${input.topic ?? 'hermetismo'}/media`,
    {
      data: {
        title: input.title,
        authorship: 'outros-autores',
        fileName: 'aula.mp3',
        bytes: body.length,
      },
      headers: CSRF,
    },
  );
  expect(created.status(), await created.text()).toBe(201);
  const { id } = (await created.json()) as { id: string };
  const sent = await api.put(`/api/v1/media/${id}/file`, {
    data: body,
    headers: { ...CSRF, 'content-type': 'application/octet-stream' },
  });
  expect(sent.status(), await sent.text()).toBe(200);
  await expect
    .poll(
      async () =>
        (
          (await (await api.get(`/api/v1/media/${id}`)).json()) as {
            status: string;
          }
        ).status,
      {
        timeout: 30_000,
      },
    )
    .toBe('ready');
  return { id, title: input.title };
}

/** What the page's media element is doing (the engine's hidden <audio> or <video>). */
export async function audioState(page: Page) {
  return page.locator('[data-media-engine]').evaluate((element) => {
    const audio = element as HTMLMediaElement;
    return {
      tag: audio.tagName,
      currentTime: audio.currentTime,
      paused: audio.paused,
      ended: audio.ended,
      duration: audio.duration,
    };
  });
}

/** The theme as the sidebar would set it, before the page loads. */
export async function useTheme(
  page: Page,
  theme: 'light' | 'dark' | 'esoteric',
) {
  await page.addInitScript(
    (value) => localStorage.setItem('kb-chat.theme', value),
    theme,
  );
}

/**
 * A person who may listen (KBC-041): speed and positions are per person, so each test
 * listens as its own new member and parallel tests never see each other's choices.
 */
export async function newListener(
  browser: Browser,
  options: PageOptions & { readonly email?: string },
): Promise<{ page: Page; email: string }> {
  const email = options.email ?? uniqueEmail('ouvinte');
  const owner = await ownerApi();
  await invite(owner, email, {
    topics: ['hermetismo'],
    features: ['search', 'media'],
  });
  await owner.dispose();
  return { page: await pageWith(browser, email, options), email };
}

/** Player specs: `page` is a fresh listener's, not the shared owner's. */
export const listenerTest = base.extend<{ page: Page }>({
  page: async (
    {
      browser,
      viewport,
    }: {
      browser: Browser;
      viewport: { width: number; height: number } | null;
    },
    use: (page: Page) => Promise<void>,
  ) => {
    const { page } = await newListener(browser, { viewport });
    await use(page);
    await page.context().close();
  },
});
